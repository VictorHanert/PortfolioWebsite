// Places the geocoder cannot resolve at all
const MANUAL_COORDINATES = {
    'Corfu': { lat: 39.624, lng: 19.922 },
    'Antigua': { lat: 14.559, lng: -90.734 },
    'Wadi Rum': { lat: 29.576, lng: 35.42 },
    'Pristina': { lat: 42.663, lng: 21.165 },
    'Luxembourg City': { lat: 49.611, lng: 6.132 },
    'AlUla': { lat: 26.608, lng: 37.923 },
};

async function geocode(name, cca2) {
    const res = await fetch(
        `https://geocoding-api.open-meteo.com/v1/search?name=${encodeURIComponent(name)}&count=10&language=en`
    );
    if (!res.ok) throw new Error(`Geocoding failed for ${name}: ${res.status}`);
    const hit = ((await res.json()).results ?? []).find((r) => r.country_code === cca2);
    await sleep(60);
    return hit ? { lat: Math.round(hit.latitude * 1000) / 1000, lng: Math.round(hit.longitude * 1000) / 1000 } : null;
}

const countries = await (await fetch(COUNTRIES_URL)).json();
const cca2ByCca3 = new Map(countries.map((c) => [c.cca3, c.cca2]));

// 1) Destinations
const destinations = JSON.parse(await readFile(SEED_FILE, 'utf8'));
const notFound = [];
for (const d of destinations) {
    if (typeof d.latitude === 'number' && typeof d.longitude === 'number') continue;

    const cca2 = cca2ByCca3.get(d.country_code);
    const point = MANUAL_COORDINATES[d.name] ?? (await geocode(GEOCODE_OVERRIDES[d.name] ?? d.name, cca2));
    if (!point) {
        notFound.push(`${d.name} (${d.country})`);
        continue;
    }
    d.latitude = point.lat;
    d.longitude = point.lng;
}
await writeFile(SEED_FILE, JSON.stringify(destinations, null, 2) + '\n', 'utf8');
console.log(`Destinations with coordinates: ${destinations.filter((d) => typeof d.latitude === 'number').length} of ${destinations.length}`);
if (notFound.length > 0) console.log(`Not found, add to GEOCODE_OVERRIDES:\n  ${notFound.join('\n  ')}`);

// 2) Origin countries: capital coordinates, falling back to the country centroid
const origins = [];
for (const c of countries.filter((country) => country.unMember)) {
    const capital = c.capital?.[0];
    const point = (capital ? await geocode(capital, c.cca2) : null) ?? {
        lat: Math.round(c.latlng[0] * 1000) / 1000,
        lng: Math.round(c.latlng[1] * 1000) / 1000,
    };
    origins.push({ code: c.cca3, name: c.name.common, ...point });
}
origins.sort((a, b) => a.name.localeCompare(b.name));
await writeFile(
    ORIGINS_FILE,
    `// Generated by scripts/fetch-geodata.mjs. Do not edit by hand.
export interface OriginCountry {
    code: string; // ISO 3166-1 alpha-3
    name: string;
    lat: number; // capital
    lng: number;
}

export const DEFAULT_ORIGIN_CODE = 'DNK';

export const originCountries: OriginCountry[] = [
${origins.map((o) => `    ${JSON.stringify(o)},`).join('\n')}
];
`,
    'utf8'
);
console.log(`Wrote ${origins.length} origin countries.`);
